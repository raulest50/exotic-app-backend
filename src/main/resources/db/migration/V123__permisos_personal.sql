-- Personal leave files. Never updates users' access assignments or existing historical documents.
CREATE TABLE configuracion_permiso_personal (
    empleado_id BIGINT PRIMARY KEY REFERENCES integrante_personal(id),
    version BIGINT NOT NULL DEFAULT 0,
    jefe_id BIGINT REFERENCES users(id),
    actualizado_en TIMESTAMP NOT NULL,
    actualizado_por_id BIGINT NOT NULL REFERENCES users(id)
);

CREATE TABLE solicitud_permiso_personal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('BORRADOR','SOLICITADA','APROBADA','RECHAZADA','ANULADA')),
    empleado_id BIGINT NOT NULL REFERENCES integrante_personal(id),
    solicitante_id BIGINT NOT NULL REFERENCES users(id),
    jefe_id BIGINT REFERENCES users(id),
    empleado_nombre VARCHAR(255) NOT NULL,
    empleado_cargo VARCHAR(255),
    solicitante_username VARCHAR(255) NOT NULL,
    jefe_nombre VARCHAR(255),
    jefe_username VARCHAR(255),
    fecha_solicitud DATE NOT NULL,
    proceso VARCHAR(255),
    motivo VARCHAR(40) CHECK (motivo IN ('CITA_TRATAMIENTO_MEDICO','CALAMIDAD_DOMESTICA','LICENCIA_REMUNERADA',
        'LICENCIA_NO_REMUNERADA','ASUNTOS_PERSONALES','DILIGENCIAS_EMPRESA','ASUNTOS_ACADEMICOS','MOVILIDAD','DIA_FAMILIA','OTROS')),
    descripcion TEXT,
    documento_soporte VARCHAR(1000),
    mecanismo_recuperacion VARCHAR(2000),
    fecha_desde DATE,
    fecha_hasta DATE,
    cantidad NUMERIC(12,2) CHECK (cantidad > 0),
    unidad VARCHAR(10) CHECK (unidad IN ('HORAS','DIAS','MESES')),
    soporte_nombre VARCHAR(255),
    soporte_content_type VARCHAR(80) CHECK (soporte_content_type IN ('application/pdf','image/png','image/jpeg')),
    soporte_sha256 VARCHAR(64),
    soporte_contenido BYTEA CHECK (octet_length(soporte_contenido) <= 5242880),
    hash_contenido VARCHAR(64),
    creado_en TIMESTAMP NOT NULL,
    actualizado_en TIMESTAMP NOT NULL,
    presentado_en TIMESTAMP,
    resuelto_en TIMESTAMP,
    motivo_decision VARCHAR(2000),
    motivo_anulacion VARCHAR(2000),
    CONSTRAINT ck_permiso_jefe_distinto CHECK (jefe_id IS NULL OR jefe_id <> solicitante_id),
    CONSTRAINT ck_permiso_fechas CHECK (fecha_hasta IS NULL OR fecha_desde IS NULL OR fecha_hasta >= fecha_desde),
    CONSTRAINT ck_permiso_soporte_completo CHECK (
        (soporte_contenido IS NULL AND soporte_nombre IS NULL AND soporte_content_type IS NULL AND soporte_sha256 IS NULL)
        OR (soporte_contenido IS NOT NULL AND soporte_nombre IS NOT NULL AND soporte_content_type IS NOT NULL AND soporte_sha256 IS NOT NULL AND length(soporte_sha256) = 64)),
    CONSTRAINT ck_permiso_presentado CHECK (estado IN ('BORRADOR','ANULADA') OR (
        jefe_id IS NOT NULL AND jefe_nombre IS NOT NULL AND jefe_username IS NOT NULL AND empleado_cargo IS NOT NULL
        AND proceso IS NOT NULL AND motivo IS NOT NULL AND descripcion IS NOT NULL
        AND fecha_desde IS NOT NULL AND fecha_hasta IS NOT NULL AND cantidad IS NOT NULL AND unidad IS NOT NULL
        AND presentado_en IS NOT NULL AND hash_contenido IS NOT NULL AND length(hash_contenido) = 64)),
    CONSTRAINT ck_permiso_decision CHECK (estado NOT IN ('APROBADA','RECHAZADA') OR resuelto_en IS NOT NULL),
    CONSTRAINT ck_permiso_rechazo_motivo CHECK (estado <> 'RECHAZADA' OR (motivo_decision IS NOT NULL AND length(trim(motivo_decision)) > 0)),
    CONSTRAINT ck_permiso_anulacion_motivo CHECK (estado <> 'ANULADA' OR (motivo_anulacion IS NOT NULL AND length(trim(motivo_anulacion)) > 0))
);

CREATE INDEX idx_permiso_solicitante_fecha ON solicitud_permiso_personal(solicitante_id, fecha_solicitud DESC, id DESC);
CREATE INDEX idx_permiso_jefe_pendiente ON solicitud_permiso_personal(jefe_id, id DESC) WHERE estado = 'SOLICITADA';
CREATE INDEX idx_permiso_estado_fecha ON solicitud_permiso_personal(estado, fecha_solicitud DESC, id DESC);

CREATE TABLE firma_permiso_personal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id BIGINT NOT NULL REFERENCES solicitud_permiso_personal(id),
    firmante_id BIGINT NOT NULL REFERENCES users(id),
    rol VARCHAR(20) NOT NULL CHECK (rol IN ('SOLICITANTE','JEFE')),
    username VARCHAR(255) NOT NULL,
    nombre VARCHAR(255) NOT NULL,
    cedula VARCHAR(30) NOT NULL,
    firmado_en TIMESTAMP NOT NULL,
    hash_contenido VARCHAR(64) NOT NULL CHECK (length(hash_contenido) = 64),
    sha256 VARCHAR(64) NOT NULL CHECK (length(sha256) = 64),
    firma_visual_version_id BIGINT REFERENCES firma_visual_usuario_version(id),
    contenido BYTEA NOT NULL CHECK (octet_length(contenido) BETWEEN 1 AND 1048576),
    UNIQUE(solicitud_id, rol)
);

CREATE TABLE evento_permiso_personal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id BIGINT REFERENCES solicitud_permiso_personal(id),
    empleado_id BIGINT REFERENCES integrante_personal(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    actor_nombre VARCHAR(255) NOT NULL,
    tipo VARCHAR(40) NOT NULL,
    creado_en TIMESTAMP NOT NULL,
    detalle VARCHAR(4000) NOT NULL,
    CHECK (solicitud_id IS NOT NULL OR empleado_id IS NOT NULL)
);
CREATE INDEX idx_evento_permiso_solicitud ON evento_permiso_personal(solicitud_id, id);
CREATE INDEX idx_evento_permiso_empleado ON evento_permiso_personal(empleado_id, id);

-- Historical evidence cannot be rewritten by later application edits.
CREATE FUNCTION impedir_mutacion_evidencia_permiso() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'La evidencia histórica de permisos es inmutable';
END;
$$;
CREATE TRIGGER trg_firma_permiso_inmutable BEFORE UPDATE OR DELETE ON firma_permiso_personal
    FOR EACH ROW EXECUTE FUNCTION impedir_mutacion_evidencia_permiso();
CREATE TRIGGER trg_evento_permiso_inmutable BEFORE UPDATE OR DELETE ON evento_permiso_personal
    FOR EACH ROW EXECUTE FUNCTION impedir_mutacion_evidencia_permiso();

CREATE FUNCTION validar_autor_firma_permiso() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    solicitud solicitud_permiso_personal%ROWTYPE;
BEGIN
    SELECT * INTO STRICT solicitud FROM solicitud_permiso_personal WHERE id = NEW.solicitud_id;
    IF NEW.hash_contenido IS DISTINCT FROM solicitud.hash_contenido THEN
        RAISE EXCEPTION 'La firma debe corresponder al contenido del expediente';
    END IF;
    IF NEW.rol = 'SOLICITANTE' AND (NEW.firmante_id <> solicitud.solicitante_id OR solicitud.estado <> 'BORRADOR') THEN
        RAISE EXCEPTION 'Solo el solicitante puede presentar su borrador';
    END IF;
    IF NEW.rol = 'JEFE' AND (NEW.firmante_id IS DISTINCT FROM solicitud.jefe_id
        OR NEW.firmante_id = solicitud.solicitante_id OR solicitud.estado <> 'SOLICITADA') THEN
        RAISE EXCEPTION 'Solo el jefe asignado puede aprobar una solicitud pendiente';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_firma_permiso_autor BEFORE INSERT ON firma_permiso_personal
    FOR EACH ROW EXECUTE FUNCTION validar_autor_firma_permiso();

CREATE FUNCTION proteger_contenido_permiso_presentado() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT (
        (OLD.estado = 'BORRADOR' AND NEW.estado IN ('BORRADOR','SOLICITADA','ANULADA'))
        OR (OLD.estado = 'SOLICITADA' AND NEW.estado IN ('APROBADA','RECHAZADA','ANULADA'))
        OR (OLD.estado IN ('APROBADA','RECHAZADA') AND NEW.estado = 'ANULADA')
        OR (OLD.estado = 'ANULADA' AND NEW.estado = 'ANULADA')
    ) THEN
        RAISE EXCEPTION 'La transición de estado del permiso no está permitida';
    END IF;
    IF OLD.estado <> 'BORRADOR' AND ROW(
        NEW.empleado_id, NEW.solicitante_id, NEW.jefe_id, NEW.empleado_nombre, NEW.empleado_cargo,
        NEW.solicitante_username, NEW.jefe_nombre, NEW.jefe_username, NEW.fecha_solicitud,
        NEW.proceso, NEW.motivo, NEW.descripcion, NEW.documento_soporte, NEW.mecanismo_recuperacion,
        NEW.fecha_desde, NEW.fecha_hasta, NEW.cantidad, NEW.unidad,
        NEW.soporte_nombre, NEW.soporte_content_type, NEW.soporte_sha256, NEW.soporte_contenido,
        NEW.hash_contenido, NEW.creado_en, NEW.presentado_en
    ) IS DISTINCT FROM ROW(
        OLD.empleado_id, OLD.solicitante_id, OLD.jefe_id, OLD.empleado_nombre, OLD.empleado_cargo,
        OLD.solicitante_username, OLD.jefe_nombre, OLD.jefe_username, OLD.fecha_solicitud,
        OLD.proceso, OLD.motivo, OLD.descripcion, OLD.documento_soporte, OLD.mecanismo_recuperacion,
        OLD.fecha_desde, OLD.fecha_hasta, OLD.cantidad, OLD.unidad,
        OLD.soporte_nombre, OLD.soporte_content_type, OLD.soporte_sha256, OLD.soporte_contenido,
        OLD.hash_contenido, OLD.creado_en, OLD.presentado_en
    ) THEN
        RAISE EXCEPTION 'El contenido del permiso presentado no puede modificarse';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_permiso_contenido_firmado BEFORE UPDATE ON solicitud_permiso_personal
    FOR EACH ROW EXECUTE FUNCTION proteger_contenido_permiso_presentado();
