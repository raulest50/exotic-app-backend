-- Cada fila representa una llegada, incluso si la cedula ya tiene otras visitas.
CREATE TABLE registro_visitante (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cedula VARCHAR(30) NOT NULL,
    nombre_completo VARCHAR(160) NOT NULL,
    edad INTEGER,
    genero VARCHAR(30),
    fecha_registro TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_registro_visitante_cedula CHECK (
        length(btrim(cedula)) > 0 AND cedula !~ '[[:cntrl:]]'),
    CONSTRAINT ck_registro_visitante_nombre CHECK (
        length(btrim(nombre_completo)) > 0 AND nombre_completo !~ '[[:cntrl:]]'),
    CONSTRAINT ck_registro_visitante_edad CHECK (edad BETWEEN 0 AND 120),
    CONSTRAINT ck_registro_visitante_genero CHECK (
        genero IN ('FEMENINO', 'MASCULINO', 'NO_BINARIO', 'OTRO', 'PREFIERO_NO_INFORMAR'))
);

CREATE INDEX idx_registro_visitante_fecha_id ON registro_visitante (fecha_registro DESC, id DESC);
